def seed():
    db = SessionLocal()
    try:
        existing = db.query(AnalysisArticle).count()
        if existing >= 5:
            print(f"이미 분석 기사 {existing}개 존재 — 스킵")
            return

        now = datetime.utcnow()
        for art in ARTICLES:
            article = AnalysisArticle(
                title=art["title"],
                summary=art["summary"],
                content=art["content"],
                category=art["category"],
                source=art["source"],
                source_name=art["source_name"],
                seo_slug=art["seo_slug"],
                published_at=now - timedelta(days=art["days_ago"]),
            )
            db.add(article)

        db.commit()
        print(f"분석 시드 기사 {len(ARTICLES)}개 등록 완료")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
