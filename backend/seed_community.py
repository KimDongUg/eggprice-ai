def seed():
    db = SessionLocal()
    try:
        existing = db.query(CommunityPost).count()
        if existing >= 20:
            print(f"이미 {existing}개 게시글이 있습니다. 시드 생략.")
            return

        now = datetime.utcnow()
        for author, title, content, days_ago, views in POSTS:
            created = now - timedelta(
                days=days_ago,
                hours=random.randint(0, 12),
                minutes=random.randint(0, 59),
            )
            post = CommunityPost(
                title=title,
                content=content,
                author_name=author,
                password=SEED_PASSWORD,
                views=views,
                created_at=created,
                updated_at=created,
            )
            db.add(post)

        db.commit()
        print(f"커뮤니티 시드 게시글 {len(POSTS)}개 등록 완료!")
    except Exception as e:
        db.rollback()
        print(f"시드 실패: {e}")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
