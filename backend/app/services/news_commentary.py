def generate_commentary(title: str, summary: str, category: str) -> str:
    """기사 제목·요약·카테고리를 분석하여 200자+ 해설을 생성합니다."""
    text = f"{title} {summary}"

    # 키워드 매칭 — 첫 매칭 우선
    for pattern, templates in _KEYWORD_RULES:
        if re.search(pattern, text):
            return random.choice(templates)

    # 카테고리 기반 폴백
    if category == "사료":
        return random.choice(_FEED_PRICE)
    if category == "산업":
        return random.choice(_INDUSTRY_GENERAL)

    return random.choice(_FALLBACK)
